  assert.deepEqual(entryAt(generated, "vendor").memory, { marked: false, mentions: [{ file: "CLAUDE.md", line: 3 }] });
  assert.deepEqual(entryAt(generated, "src/app.min.js").memory, { marked: true, mentions: [{ file: "CLAUDE.md", line: 5 }] });
