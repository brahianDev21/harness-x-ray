const execFileAsync = promisify(execFile);
const TEST_DIR = path.dirname(fileURLToPath(import.meta.url));
const HARNESS_ROOT = path.resolve(TEST_DIR, "..");
const SCAN_SCRIPT = path.join(HARNESS_ROOT, "scripts", "scan.mjs");
const SCHEMA_FILE = path.join(HARNESS_ROOT, "schemas", "measurements.schema.json");
const FIXTURES = path.join(TEST_DIR, "fixtures");
const FIXED_NOW = new Date("2026-10-18T12:00:00.000Z");
const MIB = 1024 * 1024;

const NO_RULE = { decision: "default", rule: null, source: null, reason: "no-rule-matched" };
const UNPROTECTED = { read: NO_RULE, edit: NO_RULE };

// A file of two mebibytes. Written in a temp folder only: the test repository never versions it.
const twoMebibytes = (byte = 0x2e) => Buffer.alloc(2 * MIB, byte);

// A settings file with the given project deny rules.
function settingsDeny(...rules) {
  return `${JSON.stringify({ permissions: { deny: rules } }, null, 2)}\n`;
}

// A new fixture in a temp folder, removed when the test ends.
function freshFixture(t, description = {}) {
  const fixture = makeFixture(description);
  t.after(fixture.cleanup);
  return fixture;
}

// A copy of a versioned fixture in a temp folder.
function copyOf(t, name) {
  const fixture = makeFixture({ fromDir: path.join(FIXTURES, name) });
  t.after(fixture.cleanup);
  return fixture;
}

// Runs the memory measure, then the structure measure. The ancestor walk stops at the fixture folder, so the real parent
// folders of the temp folder never count.
function structureScan(fixture) {
  return scan({
    root: fixture.root,
    measures: [
      createMemoryMeasure({ ancestorLimit: fixture.base, home: path.join(fixture.base, "no-home") }),
      structureMeasure,
    ],
    now: FIXED_NOW,
  });
}

// Runs the command line through execFile (never a shell). Resolves with the exit code and both streams.
async function runScan(args) {
  try {
    const { stdout, stderr } = await execFileAsync(process.execPath, [SCAN_SCRIPT, ...args], {
      encoding: "utf8",
      windowsHide: true,
      timeout: 120_000,
    });
    return { code: 0, stdout, stderr };
  } catch (error) {
    if (typeof error.code !== "number") throw error; // The process did not start.
    return { code: error.code, stdout: error.stdout, stderr: error.stderr };
  }
}

// Removes the meta block from the raw text. In the output, meta is a top-level key, so its block ends at the first line
// that is exactly "  },".
function withoutMetaText(raw) {
  const stripped = raw.replace(/^  "meta": \{\n[\s\S]*?^  \},\n/m, "");
  assert.notEqual(stripped, raw, "the meta block was not found");
  return stripped;
}

// The entry of a list with the given path.
const entryAt = (list, entryPath) => list.find((item) => item.path === entryPath);
// The item of the map coverage list for a top-level folder.
const dirAt = (list, dir) => list.find((item) => item.dir === dir);

// True when the list is in code-unit order of the key.
function isSortedBy(list, key) {
  return list.every((item, index) => index === 0 || list[index - 1][key] <= item[key]);
}

