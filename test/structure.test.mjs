test("the measurements schema documents every structure field and the protection verdict", () => {
  const schema = JSON.parse(fs.readFileSync(SCHEMA_FILE, "utf8"));
  const structure = schema.properties.structure;
  const keys = ["enforcementTools", "generatedFiles", "largeFiles", "mapCoverage", "tree"];
  assert.deepEqual(Object.keys(structure.properties).sort(), keys);
  assert.deepEqual([...structure.required].sort(), keys);

  const generated = structure.properties.generatedFiles.items;
  assert.deepEqual([...generated.required].sort(), Object.keys(generated.properties).sort());
  assert.deepEqual(generated.properties.kind.enum, ["folder", "file"]);
  assert.deepEqual(generated.properties.protection, { $ref: "#/$defs/protection" });

  const large = structure.properties.largeFiles.items;
  assert.deepEqual([...large.required].sort(), Object.keys(large.properties).sort());

  const coverage = structure.properties.mapCoverage;
  assert.deepEqual([...coverage.required].sort(), ["byDir", "dirs", "mentioned"]);
  assert.deepEqual([...coverage.properties.byDir.items.required].sort(), ["dir", "files", "mentioned", "mentions"]);

  assert.ok(schema.$defs.protection.properties.decision.enum.includes("mixed"));
  assert.ok(schema.$defs.protection.properties.counts, "counts is documented for mixed verdicts");
  assert.deepEqual(schema.$defs.protection.properties.layer.enum, ["user"], "layer is documented for a verdict of a user rule");
  assert.deepEqual(schema.$defs.verdict.properties.layer.enum, ["user"], "layer is documented on the secrets verdicts too");
  assert.deepEqual([...schema.$defs.entryMemory.required].sort(), ["marked", "mentions"]);
});
